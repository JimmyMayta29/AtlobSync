package routes

import (
	"github.com/SwodLore/sire-api/VENTAS/controllers"
	"github.com/gin-gonic/gin"
)

// RegisterRoutes registra los endpoints de Ventas en el grupo asignado (ej. /api/empresas/:ruc/ventas)
func RegisterRoutes(r *gin.RouterGroup) {
	r.GET("/periodos/:codLibro", controllers.GetPeriodos)
	r.GET("/periodos", controllers.GetPeriodos)
	r.POST("/importar-reemplazo-propuesta/:perTributario", controllers.ImportarReemplazoPropuesta)
	r.POST("/importar-nuevos-comprobantes/:perTributario", controllers.ImportarNuevosComprobantes)
	r.POST("/importar-comprobantes-preliminar/:perTributario", controllers.ImportarComprobantesPreliminar)
	r.POST("/importar-ajustes-posteriores/:perTributario", controllers.ImportarAjustesPosteriores)
	r.POST("/importar-ajustes-periodos-anteriores/:perTributario", controllers.ImportarAjustesPeriodosAnteriores)
	r.POST("/aceptar-propuesta/:perTributario", controllers.AceptarPropuestaRVIE)
	r.POST("/registrar-preliminar/:perTributario", controllers.RegistrarPreliminarController)
	r.POST("/exclusion-definitiva/:perTributario", controllers.ExclusionDefinitivaController)
	r.POST("/tipo-cambio-masivo/:perTributario", controllers.TipoCambioMasivoController)
	r.PUT("/editar-tipo-cambio/:perTributario", controllers.EditarTipoCambioController)
	r.DELETE("/eliminar-comprobante/:perTributario", controllers.EliminarComprobanteController)
	r.PUT("/eliminar-comprobante-preliminar/:perTributario", controllers.EliminarComprobantePreliminar)
	r.PUT("/eliminar-reemplazo/:perTributario", controllers.EliminarReemplazoPropuesta)
	r.GET("/consultar-estado-ticket", controllers.ConsultarEstadoTicket)
	r.GET("/descargar-archivo", controllers.DescargarArchivo)
	r.GET("/descargar-propuesta/:perTributario", controllers.DescargarPropuesta)
	r.GET("/descargar-no-incluidos/:perTributario", controllers.DescargarNoIncluidos)
	r.GET("/descargar-resumen/:perTributario/:codTipoResumen/:codTipoArchivo", controllers.DescargarResumen)
	r.GET("/descargar-resumen-inconsistencias/:perPeriodoTributario", controllers.DescargarResumenInconsistencias)
	r.GET("/exportar-preliminar-ventas/:perTributario", controllers.ExportarPreliminarVentas)
	r.GET("/descargar-reporte-casillas/:perTributario/:tipoReporte/:tipoDescarga", controllers.DescargarReporteCasillas)
	r.GET("/descargar-inconsistencias-preliminar/:perTributario/:numCas", controllers.DescargarInconsistenciasPreliminar)
	r.GET("/inconsistencias-comprobantes/:perTributario", controllers.DescargarInconsistenciasComprobantes)
	r.GET("/constancia-recepcion", controllers.DescargarConstanciaRecepcion)
	r.GET("/rvie-periodo/:perTributario", controllers.DescargarRVIEPorPeriodo)
	r.GET("/reporte-consolidado-periodo/:perTributario", controllers.DescargarReporteConsolidadoPorPeriodo)
	r.GET("/ajustes-posteriores/:perTributario", controllers.DescargarAjustesPosteriores)
	r.GET("/ajustes-posteriores-periodos-anteriores/:perTributario", controllers.DescargarAjustesPosterioresPeriodosAnteriores)
	r.GET("/inconsistencias-periodo/:codRegistroLibro", controllers.DescargarInconsistenciasPorPeriodo)
	r.GET("/reporte-car/:perTributario", controllers.DescargarReporteCAR)
	r.GET("/reporte-estadistico/:perTributario", controllers.DescargarReporteEstadistico)
	r.GET("/reporte-cumplimiento/:perTributario/:codLibro", controllers.DescargarReporteCumplimiento)
	r.GET("/reporte-exportadores/:perTributario", controllers.ReporteExportadores)
	r.PUT("/eliminapreliminar/:perTributario", controllers.EliminarPreliminarController)
}
